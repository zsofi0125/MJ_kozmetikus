function setLanguage(lang) {
    if (!translations[lang]) lang = 'hu';
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;

    // Update toggle button text if needed
    const toggleBtn = document.getElementById('langToggle');
    if (toggleBtn) {
        toggleBtn.textContent = lang === 'hu' ? 'EN' : 'HU';
    }

    // Translate all elements
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // If it's a placeholder, update placeholder attribute
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });
}

export function initI18n() {
    const savedLang = localStorage.getItem('lang') || 'hu';
    setLanguage(savedLang);

    const toggleBtn = document.getElementById('langToggle');
    if (toggleBtn) {
        toggleBtn.addEventListener('click', () => {
            const currentLang = localStorage.getItem('lang');
            const newLang = currentLang === 'hu' ? 'en' : 'hu';
            setLanguage(newLang);
        });
    }

    // Reveal navigation once translation is applied
    document.documentElement.classList.add('i18n-ready');
}
